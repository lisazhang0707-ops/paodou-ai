export function buildSystemPrompt(depth: AnalysisDepth, type: AnalysisType): string {
  const templateBlock = (() => {
    switch (type) {
      case "industry":
        return industryTemplate();
      case "benchmark":
        return benchmarkTemplate();
      default: {
        if (depth === "L1") return quickScanTemplate();
        return fullReportTemplate(depth === "L3");
      }
    }
  })();

  return `${SYSTEM_PROMPT}\n${templateBlock}`;
}

export function buildUserPrompt(opts: {
  name: string;
  industry?: string;
  depth: AnalysisDepth;
  type: AnalysisType;
  competitor?: string;
  geographic: string;
  researchContext?: string;
}): string {
  const parts: string[] = [];
  if (opts.researchContext) {
    parts.push(opts.researchContext, "");
  }
  parts.push("请对以下对象进行战略分析：", "");
  parts.push(`- 名称：${opts.name}`);
  if (opts.industry) parts.push(`- 行业：${opts.industry}`);
  parts.push(`- 分析深度：${opts.depth === "L1" ? "L1 快速扫描" : opts.depth === "L2" ? "L2 标准分析" : "L3 深度战略"}`);
  const typeLabel =
    opts.type === "company"
      ? "公司战略分析"
      : opts.type === "industry"
        ? "行业吸引力分析"
        : "竞争对手对标分析";
  parts.push(`- 分析类型：${typeLabel}`);
  if (opts.type === "benchmark" && opts.competitor) {
    parts.push(`- 对标公司：${opts.competitor}`);
  }
  parts.push(`- 地理范围：${opts.geographic}`);
  parts.push("");
  parts.push(`请严格按照你的方法论指南执行分析，输出完整报告。不要写"好的，我来分析"之类的开场白，直接从报告正文开始。`);
  parts.push("根据图表输出规范，在报告的合适位置嵌入 recharts 图表数据块。所有具体数据必须标注来源。");

  return parts.join("\n");
}
